-- Тенанты (NBCO) и их справочники

create table organisations (
    id         bigint generated by default as identity primary key,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    name       varchar(256) not null,
    login      varchar(32)  not null unique,
    front_id   varchar(32),
    active     boolean      not null default true,
    platform   boolean      not null default false
);

create table currencies (
    id         bigint generated by default as identity primary key,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    code       varchar(8) not null unique,
    value      varchar(8) not null
);

create table org_cards (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null,
    updated_at  timestamptz not null,
    tenant_id   bigint not null,
    pan         varchar(32) not null,
    expiry      varchar(8),
    currency_id bigint not null,
    merchant    varchar(32)
);
create index ix_org_cards_tenant on org_cards(tenant_id);
create index ix_org_cards_currency on org_cards(currency_id);

create table org_currencies (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null,
    updated_at  timestamptz not null,
    tenant_id   bigint not null,
    currency_id bigint not null,
    constraint uq_org_currency unique (tenant_id, currency_id)
);

create table org_bins (
    id         bigint generated by default as identity primary key,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    tenant_id  bigint not null,
    bin        varchar(12) not null,
    constraint uq_org_bin unique (tenant_id, bin)
);

create table branches (
    id         bigint generated by default as identity primary key,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    tenant_id  bigint not null,
    name       varchar(256) not null,
    front_id   varchar(32),
    status     varchar(16) not null
);
create index ix_branches_tenant on branches(tenant_id);
