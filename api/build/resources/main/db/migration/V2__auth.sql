-- Пользователи, роли, права, токены

create table roles (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null,
    updated_at  timestamptz not null,
    tenant_id   bigint not null,
    name        varchar(64) not null,
    description varchar(256),
    constraint uq_role_name unique (tenant_id, name)
);

create table role_permissions (
    role_id    bigint not null references roles(id) on delete cascade,
    permission varchar(40) not null,
    constraint pk_role_permission primary key (role_id, permission)
);

create table users (
    id              bigint generated by default as identity primary key,
    created_at      timestamptz not null,
    updated_at      timestamptz not null,
    tenant_id       bigint not null,
    username        varchar(64) not null,
    password_hash   varchar(255) not null,
    first_name      varchar(128),
    last_name       varchar(128),
    middle_name     varchar(128),
    birth_date      date,
    gender          varchar(16),
    phone           varchar(32),
    status          varchar(16) not null,
    branch_id       bigint,
    password_expiry date,
    super_admin     boolean not null default false,
    constraint uq_user_username unique (tenant_id, username)
);

create table user_roles (
    user_id bigint not null references users(id) on delete cascade,
    role_id bigint not null references roles(id) on delete cascade,
    constraint pk_user_role primary key (user_id, role_id)
);

create table refresh_tokens (
    id         bigint generated by default as identity primary key,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    user_id    bigint not null,
    token_hash varchar(128) not null,
    expires_at timestamptz not null,
    revoked    boolean not null default false,
    ip         varchar(64),
    user_agent varchar(256)
);
create index ix_refresh_token_hash on refresh_tokens(token_hash);
create index ix_refresh_user on refresh_tokens(user_id);

create table otp_challenges (
    id           bigint generated by default as identity primary key,
    created_at   timestamptz not null,
    updated_at   timestamptz not null,
    reference    varchar(64) not null unique,
    user_id      bigint not null,
    code_hash    varchar(128) not null,
    expires_at   timestamptz not null,
    attempts     int not null default 0,
    max_attempts int not null default 5,
    consumed     boolean not null default false
);
create index ix_otp_ref on otp_challenges(reference);
