-- Журнал аудита

create table audit_events (
    id             bigint generated by default as identity primary key,
    created_at     timestamptz not null,
    updated_at     timestamptz not null,
    tenant_id      bigint,
    user_id        bigint,
    action         varchar(64) not null,
    entity_type    varchar(64),
    entity_id      varchar(64),
    details        varchar(2000),
    correlation_id varchar(64)
);
create index ix_audit_tenant on audit_events(tenant_id);
create index ix_audit_action on audit_events(action);
create index ix_audit_entity on audit_events(entity_type, entity_id);
create index ix_audit_correlation on audit_events(correlation_id);
