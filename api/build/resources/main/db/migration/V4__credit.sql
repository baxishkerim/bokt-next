-- Кредиты (заявки + платёжные атрибуты)

create table credits (
    id              bigint generated by default as identity primary key,
    created_at      timestamptz not null,
    updated_at      timestamptz not null,
    tenant_id       bigint not null,
    client_id       bigint not null,
    client_card_pan varchar(32) not null,
    amount_minor    bigint not null,
    currency_id     bigint not null,
    status          varchar(16) not null,
    branch_id       bigint,
    secret_word     varchar(128),
    description     varchar(512),
    file_id         bigint,
    charge_guid     varchar(32),
    topup_guid      varchar(32),
    charge_rrn      varchar(32),
    topup_rrn       varchar(32),
    created_by      bigint,
    approved_by     bigint,
    approved_at     timestamptz,
    cancelled_by    bigint
);
create index ix_credit_tenant on credits(tenant_id);
create index ix_credit_client on credits(client_id);
create index ix_credit_status on credits(status);
create index ix_credit_client_pan on credits(client_card_pan);
create index ix_credit_file on credits(file_id);
